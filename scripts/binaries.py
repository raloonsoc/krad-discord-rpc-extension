#!/usr/bin/env python3
"""Rewrites the program binaries in extension.toml.

    scripts/binaries.py local
        Point every platform at its locally built binary in bin/ (what
        scripts/install.sh builds). Use this to run your own build.

    scripts/binaries.py release <version> <assets-dir> [<owner/repo>]
        Point every platform whose binary is in <assets-dir> at the GitHub
        Release download for tag v<version>, with its SHA-256, and set the
        manifest version. The release workflow runs this.

Only the block between the BEGIN/END BINARIES markers and the top-level
`version` line are changed.
"""

import hashlib
import os
import re
import sys
from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "extension.toml"
BEGIN = "# BEGIN BINARIES"
END = "# END BINARIES"
DEFAULT_REPO = "raloonsoc/krad-discord-rpc-extension"

# Krad ADE platform target -> binary name, in bin/ and as a release asset.
PLATFORMS = [
    ("darwin_arm64", "krad-discord-rpc-darwin-arm64"),
    ("darwin_x64", "krad-discord-rpc-darwin-x64"),
    ("linux_x64", "krad-discord-rpc-linux-x64"),
    ("linux_arm64", "krad-discord-rpc-linux-arm64"),
    ("win_x64", "krad-discord-rpc-win-x64.exe"),
    ("win_arm64", "krad-discord-rpc-win-arm64.exe"),
]


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        for chunk in iter(lambda: file.read(1 << 16), b""):
            digest.update(chunk)
    return digest.hexdigest()


def local_block() -> str:
    return "\n".join(
        f'[[program.binary]]\ntargets = ["{target}"]\npath = "bin/{name}"\n'
        for target, name in PLATFORMS
    )


def release_block(version: str, assets: Path, repo: str) -> str:
    entries = []
    for target, name in PLATFORMS:
        asset = assets / name
        if not asset.is_file():
            print(f"warning: no {name}; {target} gets no binary", file=sys.stderr)
            continue
        url = f"https://github.com/{repo}/releases/download/v{version}/{name}"
        entries.append(
            f'[[program.binary]]\ntargets = ["{target}"]\n'
            f'url = "{url}"\nsha256 = "{sha256(asset)}"\n'
        )
    if not entries:
        sys.exit(f"no binaries found in {assets}")
    return "\n".join(entries)


def replace_block(text: str, block: str, note: str) -> str:
    pattern = re.compile(
        rf"^{re.escape(BEGIN)}.*?^{re.escape(END)}[^\n]*$", re.DOTALL | re.MULTILINE
    )
    if not pattern.search(text):
        sys.exit(f"{MANIFEST.name}: missing the {BEGIN} / {END} markers")
    replacement = f"{BEGIN} ({note})\n{block}{END}"
    return pattern.sub(lambda _: replacement, text, count=1)


def main() -> None:
    args = sys.argv[1:]
    text = MANIFEST.read_text(encoding="utf-8")
    if args == ["local"]:
        text = replace_block(
            text, local_block(), "local builds; run scripts/binaries.py to change"
        )
    elif len(args) in (3, 4) and args[0] == "release":
        version, assets = args[1].removeprefix("v"), Path(args[2])
        if not re.fullmatch(r"\d+\.\d+\.\d+([-+][0-9A-Za-z.-]+)?", version):
            sys.exit(f"not a version: {version}")
        repo = args[3] if len(args) == 4 else os.environ.get("GITHUB_REPOSITORY", DEFAULT_REPO)
        text = replace_block(
            text,
            release_block(version, assets, repo),
            f"release v{version}; generated by scripts/binaries.py",
        )
        text, count = re.subn(
            r'^version = "[^"]*"$', f'version = "{version}"', text, count=1, flags=re.MULTILINE
        )
        if count != 1:
            sys.exit(f"{MANIFEST.name}: no top-level version line")
    else:
        sys.exit(__doc__)
    MANIFEST.write_text(text, encoding="utf-8")
    print(f"updated {MANIFEST.name}")


if __name__ == "__main__":
    main()
